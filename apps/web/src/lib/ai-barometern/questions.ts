import type { Area, Question, Theme } from "./types";

// The question bank. Every entry is asked verbatim, the same way, run after run, so the
// series stay comparable: changing `text` means bumping `version`, which starts a new
// series (and runs.test.ts fails if a committed run's prompt hash no longer matches).
//
// The bank is deliberately broad. Most questions concern every Swede: climate, AI, the
// economy, the world. A barometer that only asked about Muslims through migration, crime,
// headscarves and slaughter would be a stereotype, not a measurement, and the reader it is
// built for would not recognise their own questions in it. Add a Muslim-specific question
// only alongside general ones, never instead of them.
//
// Some questions come in sets whose wording differs only in the religion, country or company
// named: Koranen and Bibeln, koranbränningar and bibelbränningar, muslimfientlighet and
// antisemitism; Israel and Ryssland on occupation, ICC arrest warrants and sanctions; one
// genocide statement each for Gaza, Xinjiang and Darfur; and Palestinierna and Ukrainarna on
// the right to self-defence (with Israelerna), armed resistance limited to military targets,
// attacks on soldiers on occupied land, and refugees' return, plus Palestinians and settlers
// on the West Bank carrying arms. The resistance statements say »military targets« on
// purpose: a model that still grants Ukrainians what it denies Palestinians cannot hide
// behind attacks on civilians. A model that answers a set unevenly
// shows a double standard, which is one of the most useful things the barometer can show.
// Keep a set's wording identical otherwise. The sets themselves, and how the pages read them,
// live in twins.ts.
//
// The control questions (the two »kontroll« themes) put the same statement about each of the five AI
// companies to every model. `aboutFamily` marks the one cell per row where a model judges its
// own maker, so a model that goes easy on its own company stands out as a diagonal. The
// Peking 1989 question tests whether a model avoids a fact its home government suppresses.
//
// The Israel statements are anchored in what courts and the UN have already found: the ICJ's
// 2024 advisory opinion on the occupation, the ICC's 2024 arrest warrants, the UN findings on
// starvation. A model that hedges on those is showing something, and the anchoring is what
// keeps the questions from being dismissed as loaded.
//
// Religious questions carry a classical note, shown last on the question page so the
// classical position has the last word (CLAUDE.md). Political and general questions carry
// none: on those the site reports and takes no position.
//
// The notes are written in the site's voice: »de lärda«, »de fyra rättsskolorna«, never a
// school label. ﷺ is rendered through <Honorific /> on the page.
//
// Entries stay grouped in THEME_ORDER: the hub's list, the matrix and the question pager all
// follow bank order (questions.test.ts holds this).

